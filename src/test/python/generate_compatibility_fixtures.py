"""Generate oracle fixtures with Python neologdn 0.5.6 (not needed to run Maven tests).

Usage: python generate_compatibility_fixtures.py [--extended] [--output PATH]
The extended corpus exercises every non-surrogate BMP code point and more random cases.
"""
import argparse
import base64
import random
from pathlib import Path

import neologdn


def encoded(text):
    return base64.b64encode(text.encode("utf-8")).decode("ascii")


def generate(extended=False):
    rng = random.Random(20261024)
    modes = ["remove", "ignore", "normalize", "normalize_zenkaku", "unknown"]

    def normalize(text, repeat=0, remove_space=True, maximum=8, tilde="remove"):
        expected = neologdn.normalize(text, repeat, remove_space, maximum, tilde)
        return "\t".join(["normalize", encoded(text), str(repeat), str(remove_space).lower(),
                          str(maximum), tilde, encoded(expected)])

    def shorten(text, repeat, maximum):
        expected = neologdn.shorten_repeat(text, repeat, maximum)
        return "\t".join(["shorten", encoded(text), str(repeat), "true", str(maximum),
                          "remove", encoded(expected)])

    # All mapped blocks together, plus voiced-mark combinations and space boundaries.
    yield normalize("".join(chr(c) for c in range(0xFF00, 0xFFF0)))
    yield normalize("“”‘’¥")
    for text in ["", " ", "　", "abc   ", "  巴　マミ  ", "A ～あ", "A ˗あ", "A ーあ",
                 "(ﾟ∀ﾟ )", "😀 あ", "𠮷 A", "A\tあ\n", "\x00あ\x00", "~∼∾〜〰～"]:
        for space in [True, False]:
            for tilde in modes:
                yield normalize(text, remove_space=space, tilde=tilde)
    for kana in "カキクケコサシスセソタチツテトハヒフヘホウうはひふへほあｶﾊｳ😀":
        for mark in "ﾞﾟ゛゜":
            yield normalize(kana + mark)
    for text in ["aa", "aaa", "aaaa", "abab", "ababab", "abcabcabc!", "😀😀😀😀",
                 "𠮷😀𠮷😀𠮷😀!", "abcdefghabcdefghabcdefgh!", "aaaaaaaaabaaaaaaaaab!"]:
        for repeat in [0, 1, 2, 4]:
            for maximum in [0, 1, 8]:
                yield shorten(text, repeat, maximum)

    alphabet = " abAB*+\t\n\x00　漢字かなカナうはほｶﾊｳﾞﾟ゛゜ー－˗−~∼∾〜〰～“”‘’¥＂＇＼｀😀𠮷éΩ"
    for _ in range(20000 if extended else 160):
        text = "".join(rng.choice(alphabet) for _ in range(rng.randrange(60)))
        repeat = rng.choice([0, 1, 2, 3, 6])
        maximum = rng.choice([0, 1, 2, 8, 11, 2147483647])
        yield normalize(text, repeat, rng.choice([True, False]), maximum, rng.choice(modes))
        pattern = "".join(rng.choice(alphabet) for _ in range(rng.randint(1, 12)))
        text = text[:rng.randrange(4)] + pattern * rng.randint(1, 8) + text[-rng.randrange(4):]
        yield shorten(text, repeat, maximum)

    if extended:
        for code_point in range(0x10000):
            if not 0xD800 <= code_point <= 0xDFFF:
                yield normalize(chr(code_point))
        for _ in range(1000):
            text = chr(rng.randrange(0x10000, 0x110000))
            yield normalize(text + " あ " + text)
            yield shorten(text * 6, 1, 8)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--extended", action="store_true")
    parser.add_argument("--output", type=Path,
                        default=Path(__file__).resolve().parents[1] / "resources/python-0.5.6.tsv")
    args = parser.parse_args()
    if neologdn.__version__ != "0.5.6":
        raise SystemExit("Use neologdn 0.5.6 to keep the compatibility target pinned")
    rows = list(generate(args.extended))
    args.output.write_text("# Generated by neologdn 0.5.6; text columns are UTF-8 Base64\n"
                           + "\n".join(rows) + "\n", encoding="utf-8")
    print(f"Wrote {len(rows)} cases to {args.output}")


if __name__ == "__main__":
    main()
